class PresentValidationTests(unittest.TestCase):
    """原始回调必须与有效概要逐实例一致。 / Raw callbacks must agree with each valid summary scenario."""

    def events(self, instances=(0, 0, 1, 1)):
        """创建逐实例有序的成功回调。 / Creates successful callbacks ordered within each player."""
        return [{"asset": "effect.ktx", "count": "2", "instance": str(instance), "elapsed_ns": str(index + 1), "phase": "measure"}
                for index, instance in enumerate(instances)]

    def test_exact_frames_and_instance_coverage_pass(self):
        RUNNER.validate_presents([summary(count=2, submitted_frames="4")], self.events(), [("effect", 2)])

    def test_frame_count_mismatch_fails(self):
        with self.assertRaisesRegex(RuntimeError, "presents.csv mismatch"):
            RUNNER.validate_presents([summary(count=2, submitted_frames="5")], self.events(), [("effect", 2)])

    def test_missing_instance_fails_even_if_total_frames_match(self):
        with self.assertRaisesRegex(RuntimeError, "presents.csv mismatch"):
            RUNNER.validate_presents([summary(count=2, submitted_frames="4")], self.events((0, 0, 0, 0)), [("effect", 2)])

    def test_missing_trace_or_submitted_frames_fails(self):
        for row in (summary(count=2), summary(count=2, submitted_frames="4")):
            with self.subTest(row=row), self.assertRaises(RuntimeError):
                RUNNER.validate_presents([row], [], [("effect", 2)])

    def test_count_zero_and_expected_failed_scenarios_need_no_events(self):
        RUNNER.validate_presents([summary(count=0, submitted_frames="0"), summary(count=16, valid="false")], [],
                                [("effect", 0), ("effect", 16)])

    def test_corrupt_events_fail(self):
        changes = ({"asset": "other.ktx"}, {"count": "8"}, {"instance": "2"}, {"instance": "not-an-int"},
                   {"elapsed_ns": "-1"}, {"elapsed_ns": "not-an-int"}, {"phase": "memory"})
        for change in changes:
            events = self.events()
            events[0].update(change)
            with self.subTest(change=change), self.assertRaises(RuntimeError):
                RUNNER.validate_presents([summary(count=2, submitted_frames="4")], events, [("effect", 2)])

    def test_nonmonotonic_instance_times_fail(self):
        events = self.events()
        events[1]["elapsed_ns"] = events[0]["elapsed_ns"]
        with self.assertRaisesRegex(RuntimeError, "Corrupt presents.csv event"):
            RUNNER.validate_presents([summary(count=2, submitted_frames="4")], events, [("effect", 2)])


