    def test_dynamic_columns_and_save_before_next_launch(self):
        self.plan.append({"repeat": 2, "trial": 2, "asset": "effect", "counts": [1], "run_id": "run-2"})
        active = [0]

        def wait(*unused):
            if active[0]:
                self.assertEqual(len(read_rows(self.output)), 1)
                self.assertEqual(len(read_rows(self.samples)), 1)
                self.assertEqual(len(read_rows(self.presents)), 1)
            active[0] += 1

        def remote(adb, name, optional=False):
            if name == "bench.csv":
                key = "first_metric" if active[0] == 1 else "later_metric"
                return dataset([summary(**{key: str(active[0])})])
            return self.standard_remote(adb, name, optional)

        with mock.patch.object(RUNNER, "wait_done", side_effect=wait), mock.patch.object(RUNNER, "read_remote_csv", side_effect=remote):
            self.run_plan()
        rows = read_rows(self.output)
        self.assertEqual([row["run_id"] for row in rows], ["run-1", "run-2"])
        self.assertEqual([row["repeat"] for row in rows], ["1", "2"])
        self.assertEqual([row["trial"] for row in rows], ["1", "2"])
        self.assertEqual(rows[0]["first_metric"], "1")
        self.assertEqual(rows[0]["later_metric"], "")
        self.assertEqual(rows[1]["later_metric"], "2")

